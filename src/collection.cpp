#include "vtapi/model/collection.hpp"

namespace vtapi {
namespace {

void parse_string_array(const nlohmann::json& value, std::vector<std::string>& out) {
    if (!value.is_array())
        return;
    for (const auto& item : value) {
        if (item.is_string())
            out.push_back(item.get<std::string>());
    }
}

CollectionRangeStats range_stats_from_json(const nlohmann::json& root) {
    CollectionRangeStats stats;
    if (!root.is_object())
        return stats;
    stats.min = root.value("min", 0.0);
    stats.max = root.value("max", 0.0);
    stats.avg = root.value("avg", 0.0);
    return stats;
}

void parse_attributes(const nlohmann::json& attr, Collection& c) {
    if (!attr.is_object())
        return;

    c.creation_date = attr.value("creation_date", 0);
    c.description = attr.value("description", "");
    c.description_html = attr.value("description_html", "");
    c.domains_count = attr.value("domains_count", 0);
    c.files_count = attr.value("files_count", 0);
    c.ip_addresses_count = attr.value("ip_addresses_count", 0);
    c.last_modification_date = attr.value("last_modification_date", 0);
    c.link = attr.value("link", "");
    c.name = attr.value("name", "");
    c.recent_activity_relative_change =
        attr.value("recent_activity_relative_change", 0.0);
    c.references_count = attr.value("references_count", 0);
    c.source_region = attr.value("source_region", "");
    c.sponsor_region = attr.value("sponsor_region", "");
    c.status = attr.value("status", "");
    c.tlp = attr.value("tlp", "");
    c.urls_count = attr.value("urls_count", 0);

    if (attr.contains("alt_names"))
        parse_string_array(attr.at("alt_names"), c.alt_names);
    if (attr.contains("autogenerated_tags"))
        parse_string_array(attr.at("autogenerated_tags"), c.autogenerated_tags);
    if (attr.contains("tags"))
        parse_string_array(attr.at("tags"), c.tags);
    if (attr.contains("targeted_industries"))
        parse_string_array(attr.at("targeted_industries"), c.targeted_industries);
    if (attr.contains("targeted_regions"))
        parse_string_array(attr.at("targeted_regions"), c.targeted_regions);
    if (attr.contains("top_icon_md5"))
        parse_string_array(attr.at("top_icon_md5"), c.top_icon_md5);

    if (attr.contains("recent_activity_summary") &&
        attr.at("recent_activity_summary").is_array()) {
        for (const auto& item : attr.at("recent_activity_summary")) {
            if (item.is_number_integer())
                c.recent_activity_summary.push_back(item.get<int64_t>());
        }
    }

    if (attr.contains("summary_stats") && attr.at("summary_stats").is_object()) {
        const auto& summary = attr.at("summary_stats");
        c.summary_stats.first_submission_date =
            range_stats_from_json(summary.value("first_submission_date",
                                                nlohmann::json::object()));
        c.summary_stats.last_submission_date =
            range_stats_from_json(summary.value("last_submission_date",
                                                nlohmann::json::object()));
        c.summary_stats.files_detections =
            range_stats_from_json(summary.value("files_detections",
                                                nlohmann::json::object()));
        c.summary_stats.urls_detections =
            range_stats_from_json(summary.value("urls_detections",
                                                nlohmann::json::object()));
    }
}

void parse_collection_object(const nlohmann::json& data, Collection& c) {
    if (!data.is_object())
        return;
    c.type = data.value("type", "");
    c.id = data.value("id", "");
    if (data.contains("links") && data.at("links").is_object() &&
        data.at("links").contains("self") && data.at("links").at("self").is_string())
        c.self_link = data.at("links").at("self").get<std::string>();
    if (data.contains("attributes"))
        parse_attributes(data.at("attributes"), c);
}

std::string link_value(const nlohmann::json& links, const char* key) {
    if (!links.is_object() || !links.contains(key))
        return {};
    const auto& value = links.at(key);
    if (value.is_string())
        return value.get<std::string>();
    if (value.is_object() && value.contains("href") && value.at("href").is_string())
        return value.at("href").get<std::string>();
    return {};
}

} // namespace

Collection collection_from_json(const nlohmann::json& root) {
    Collection c;
    c.raw = root;
    if (!root.is_object())
        return c;
    if (root.contains("data"))
        parse_collection_object(root.at("data"), c);
    else
        parse_collection_object(root, c);
    return c;
}

CollectionList collection_list_from_json(const nlohmann::json& root) {
    CollectionList list;
    list.raw = root;
    if (!root.is_object())
        return list;

    if (root.contains("meta") && root.at("meta").is_object())
        list.count = root.at("meta").value("count", 0);
    if (root.contains("links") && root.at("links").is_object()) {
        list.self_link = link_value(root.at("links"), "self");
        list.next_link = link_value(root.at("links"), "next");
    }
    if (root.contains("data") && root.at("data").is_array()) {
        for (const auto& item : root.at("data")) {
            if (item.is_object())
                list.data.push_back(collection_from_json(item));
        }
    }
    return list;
}

} // namespace vtapi
