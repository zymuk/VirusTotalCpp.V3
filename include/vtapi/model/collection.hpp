#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include <nlohmann/json.hpp>

namespace vtapi {

// min/max/avg block used by Collection::summary_stats. Kept as doubles because
// the v3 payload can report averages with a fractional part.
struct CollectionRangeStats {
    double min = 0.0;
    double max = 0.0;
    double avg = 0.0;
};

// Aggregated statistics across all IoCs contained in a collection.
struct CollectionSummaryStats {
    CollectionRangeStats first_submission_date;
    CollectionRangeStats last_submission_date;
    CollectionRangeStats files_detections;
    CollectionRangeStats urls_detections;
};

// One descriptor accepted by add/remove collection items. For file/domain/IP
// objects set type + id; for URL objects set type = "url" and either url (raw
// URL) or id (the URL's sha256 identifier).
struct CollectionElement {
    std::string type;
    std::string id;
    std::string url;
};

// Parsed GET /collections/{id} object (v3 JSON). Field names and types follow
// data.attributes.* rather than another client library's shape.
struct Collection {
    std::string type;       // data.type ("collection")
    std::string id;         // data.id
    std::string self_link;  // data.links.self

    // --- data.attributes.* ---
    std::vector<std::string> alt_names;
    std::vector<std::string> autogenerated_tags;
    int64_t creation_date = 0;
    std::string description;
    std::string description_html;
    int64_t domains_count = 0;
    int64_t files_count = 0;
    int64_t ip_addresses_count = 0;
    int64_t last_modification_date = 0;
    std::string link;
    std::string name;
    double recent_activity_relative_change = 0.0;
    std::vector<int64_t> recent_activity_summary;
    int64_t references_count = 0;
    std::string source_region;
    std::string sponsor_region;
    std::string status;
    CollectionSummaryStats summary_stats;
    std::vector<std::string> tags;
    std::vector<std::string> targeted_industries;
    std::vector<std::string> targeted_regions;
    std::string tlp;
    std::vector<std::string> top_icon_md5;
    int64_t urls_count = 0;

    // Full raw object preserved for callers that need extra fields.
    nlohmann::json raw;
};

// Response of GET /collections (premium). Pagination links are preserved as
// returned by v3; next_link is empty when there are no more pages.
struct CollectionList {
    int64_t count = 0;
    std::string self_link;
    std::string next_link;
    std::vector<Collection> data;
    nlohmann::json raw;
};

Collection collection_from_json(const nlohmann::json& root);
CollectionList collection_list_from_json(const nlohmann::json& root);

} // namespace vtapi
